// Builds small copies of the rounded Chinese font that hold only the characters this site uses.
// The full font ships as 118 files of about 146KB each; a page would pull megabytes of it.
//
//   npm run dev     every character in src/, so any page looks right while writing
//   npm run build   (--core) only the characters of the shared frame: header, footer, buttons and
//                   script text. scripts/page-fonts.mjs then gives each built page a second small
//                   font with just the characters of that page, so no page downloads the whole set.
//
// Writes src/fonts/, src/styles/fonts.css and, for --core, src/fonts/core.txt.
import fs from 'node:fs';
import path from 'node:path';
import { ALWAYS, FAMILY, subset } from './font-subset.mjs';

const OUT = 'src/fonts';
const core = process.argv.includes('--core');
// The shared frame. Pages, posts and diagrams are left to page-fonts.mjs in a build.
const FRAME = ['src/layouts', 'src/components', 'src/scripts', 'src/styles', 'src/site.ts'];
const SKIP = ['src/components/diagrams', OUT, 'src/styles/fonts.css'];

const walk = (p) => {
  if (SKIP.includes(p)) return [];
  if (fs.statSync(p).isDirectory()) return fs.readdirSync(p).flatMap((n) => walk(path.join(p, n)));
  return /\.(astro|mdx?|ts|css|svg)$/.test(p) ? [p] : [];
};
const used = new Set(ALWAYS);
for (const file of (core ? FRAME : ['src']).flatMap(walk)) for (const ch of fs.readFileSync(file, 'utf8')) used.add(ch.codePointAt(0));

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const { rules, bytes, files } = await subset(used, {
  base: '../fonts/',
  name: (face) => `${face.name}.woff2`,
  write: (file, data) => fs.writeFileSync(`${OUT}/${file}`, data),
});
if (!files) throw new Error('no font files were produced');
fs.writeFileSync('src/styles/fonts.css', `/* Generated by scripts/make-fonts.mjs. Do not edit. ${FAMILY}, SIL Open Font License 1.1. */\n${rules}`);
if (core) fs.writeFileSync(`${OUT}/core.txt`, String.fromCodePoint(...used));
console.log(`fonts${core ? ' (shared frame)' : ''}: ${used.size} characters in ${files} files, ${(bytes / 1024).toFixed(0)}KB in total`);
