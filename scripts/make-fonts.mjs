// Builds a small copy of the rounded Chinese font that holds only the characters this site uses.
// The full font (Chiron GoRound TC, OFL-1.1) ships as 118 files of about 146KB each; a page would
// pull megabytes of it. This reads every character in src/, cuts each font file down to the
// characters actually used, and writes src/fonts/ plus src/styles/fonts.css.
// Runs automatically before `npm run dev` and `npm run build`.
import fs from 'node:fs';
import path from 'node:path';
import subsetFont from 'subset-font';

const PKG = 'node_modules/@fontsource-variable/chiron-goround-tc';
const OUT = 'src/fonts';
const FAMILY = 'Chiron GoRound TC';

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  if (e.isDirectory()) return p === OUT ? [] : walk(p);
  return /\.(astro|mdx?|ts|css|svg)$/.test(e.name) && p !== 'src/styles/fonts.css' ? [p] : [];
});
const used = new Set();
for (const file of walk('src')) for (const ch of fs.readFileSync(file, 'utf8')) used.add(ch.codePointAt(0));
// Printable ASCII and common punctuation are always kept, so new English text needs no rebuild.
for (let c = 0x20; c < 0x7f; c++) used.add(c);
for (const ch of '，。、；：！？（）「」『』《》〈〉…—～·•©') used.add(ch.codePointAt(0));

const inRanges = (ranges) => {
  const hit = [];
  for (const part of ranges.split(',')) {
    const [a, b = a] = part.trim().replace(/^U\+/i, '').split('-').map((h) => parseInt(h, 16));
    for (const c of used) if (c >= a && c <= b) hit.push(c);
  }
  return hit.sort((x, y) => x - y);
};

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const css = fs.readFileSync(`${PKG}/index.css`, 'utf8');
const faces = [...css.matchAll(/url\(\.\/files\/([^)]+)\)[^;]*;\s*unicode-range:\s*([^;]+);/g)];
let rules = `/* Generated by scripts/make-fonts.mjs. Do not edit. ${FAMILY}, SIL Open Font License 1.1. */\n`;
let total = 0, files = 0, glyphs = 0;
for (const [, file, ranges] of faces) {
  const chars = inRanges(ranges);
  if (!chars.length) continue;
  const text = String.fromCodePoint(...chars);
  // Keep only the weights the site uses.
  const small = await subsetFont(fs.readFileSync(`${PKG}/files/${file}`), text, { targetFormat: 'woff2', variationAxes: { wght: { min: 400, max: 900 } } });
  const name = file.replace('-wght-normal', '');
  fs.writeFileSync(`${OUT}/${name}`, small);
  const range = chars.map((c) => `U+${c.toString(16)}`).join(',');
  rules += `@font-face{font-family:'${FAMILY}';font-style:normal;font-display:swap;font-weight:400 900;src:url(../fonts/${name}) format('woff2');unicode-range:${range}}\n`;
  total += small.length; files++; glyphs += chars.length;
}
if (!files) throw new Error('no font files were produced');
fs.writeFileSync('src/styles/fonts.css', rules);
console.log(`fonts: ${glyphs} characters in ${files} files, ${(total / 1024).toFixed(0)}KB in total`);
